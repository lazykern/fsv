use crate::model::{Kind, Node};
use crate::quote::shlex_quote as q;

fn join_cond(parts: &[&str]) -> String {
    parts
        .iter()
        .filter(|p| !p.is_empty())
        .copied()
        .collect::<Vec<_>>()
        .join("; and ")
}

fn fish_cond(path: &[String]) -> String {
    path.iter()
        .map(|p| format!("__fish_seen_subcommand_from {}", q(p)))
        .collect::<Vec<_>>()
        .join("; and ")
}

fn direct_subs(cmd: &Node) -> Vec<&Node> {
    cmd.subcommands
        .iter()
        .filter(|s| s.path.len() == cmd.path.len() + 1)
        .collect()
}

fn last(path: &[String]) -> &str {
    path.last().map_or("", String::as_str)
}

fn fish_lines(cmd: &Node, prog: &str, exe: &str, lines: &mut Vec<String>) {
    let path = &cmd.path[1..];
    let cond = fish_cond(path);

    let subs = direct_subs(cmd);
    let mut subcommand_absent = String::new();
    if !subs.is_empty() {
        let not_yet: Vec<String> = subs.iter().map(|s| q(last(&s.path))).collect();
        subcommand_absent = format!("not __fish_seen_subcommand_from {}", not_yet.join(" "));
        let full_cond = join_cond(&[&cond, &subcommand_absent]);
        for sub in &subs {
            let mut line = format!(
                "complete -c {prog} -f -n '{full_cond}' -a {}",
                q(last(&sub.path))
            );
            if !sub.help.is_empty() {
                line.push_str(&format!(" -d {}", q(&sub.help)));
            }
            lines.push(line);
        }
    }

    let value_flags: Vec<String> = cmd
        .params
        .iter()
        .filter(|p| p.takes_value())
        .flat_map(|p| p.flags.iter().map(|f| q(f)))
        .collect();
    let not_value_prev = if value_flags.is_empty() {
        String::new()
    } else {
        format!(
            "not contains -- (commandline -opc)[-1] {}",
            value_flags.join(" ")
        )
    };
    let flag_guard = join_cond(&[&cond, &not_value_prev]);
    let root_scope = if path.is_empty() {
        subcommand_absent.as_str()
    } else {
        ""
    };

    for p in &cmd.params {
        let param_guard = join_cond(&[&flag_guard, root_scope]);
        let n_flag_cond = if param_guard.is_empty() {
            String::new()
        } else {
            format!(" -n '{param_guard}'")
        };
        for flag in &p.flags {
            lines.push(format!("complete -c {prog} -f{n_flag_cond} -a {}", q(flag)));
        }
        let flags_q: Vec<String> = p.flags.iter().map(|f| q(f)).collect();
        let prev = format!("contains -- (commandline -opc)[-1] {}", flags_q.join(" "));
        match &p.kind {
            Kind::Static(values) if !values.is_empty() => {
                let vc = join_cond(&[&cond, &prev, root_scope]);
                for (val, desc) in values.iter() {
                    let mut line = format!("complete -c {prog} -f -n '{vc}' -a {}", q(val));
                    if !desc.is_empty() {
                        line.push_str(&format!(" -d {}", q(desc)));
                    }
                    lines.push(line);
                }
            }
            Kind::Dynamic {
                completer,
                resource,
            } => {
                let vc = join_cond(&[&cond, &prev, root_scope]);
                let resource = resource.as_deref().unwrap_or("-");
                let extra = if completer == "complete_lookup_query" {
                    " -- (commandline -opc)"
                } else {
                    ""
                };
                let call = format!(
                    "(FSV_THIN_COMPLETE=1 {exe} _complete fish {completer} {resource} (commandline -ct){extra})"
                );
                lines.push(format!("complete -c {prog} -n '{vc}' -a \"{call}\""));
            }
            _ => {}
        }
    }

    for sub in &cmd.subcommands {
        fish_lines(sub, prog, exe, lines);
    }
}

/// `_emit_fish`.
pub fn emit_fish(root: &Node, prog: &str, exe: &str) -> String {
    let mut lines = vec![
        format!("# Generated by {prog} completion install -- do not edit"),
        format!("# Regenerate: {prog} completion install fish"),
        String::new(),
        format!("complete -c {prog} -f"),
        String::new(),
    ];
    fish_lines(root, prog, exe, &mut lines);
    lines.join("\n") + "\n"
}

struct Case<'a> {
    key: String,
    node: &'a Node,
}

/// Port of fsv.completion_gen._collect_bash and fsv.completion_gen._collect_zsh,
/// which are the same walk; the subcommand and flag lists come from
/// `completions` when emitting.
fn collect<'a>(cmd: &'a Node, cases: &mut Vec<Case<'a>>) {
    cases.push(Case {
        key: cmd.path[1..].join(" "),
        node: cmd,
    });
    for sub in &cmd.subcommands {
        collect(sub, cases);
    }
}

fn sorted_cases(root: &Node) -> Vec<Case<'_>> {
    let mut cases = Vec::new();
    collect(root, &mut cases);
    cases.sort_by_key(|c| std::cmp::Reverse(c.key.split_whitespace().count()));
    cases
}

type ValueCases<'a> = (Vec<(&'a str, String)>, Vec<(&'a str, &'a str, &'a str)>);

fn value_cases(node: &Node) -> ValueCases<'_> {
    let mut stat = Vec::new();
    let mut dynamic = Vec::new();
    for p in &node.params {
        for f in &p.flags {
            match &p.kind {
                Kind::Static(values) if !values.is_empty() => {
                    stat.push((
                        f.as_str(),
                        values.iter().map(|(v, _)| *v).collect::<Vec<_>>().join(" "),
                    ));
                }
                Kind::Dynamic {
                    completer,
                    resource,
                } => {
                    dynamic.push((
                        f.as_str(),
                        completer.as_str(),
                        resource.as_deref().unwrap_or("-"),
                    ));
                }
                _ => {}
            }
        }
    }
    (stat, dynamic)
}

fn completions(node: &Node) -> Vec<&str> {
    let mut out: Vec<&str> = direct_subs(node).iter().map(|s| last(&s.path)).collect();
    out.extend(
        node.params
            .iter()
            .flat_map(|p| p.flags.iter().map(String::as_str)),
    );
    out
}

/// `_emit_bash`.
pub fn emit_bash(root: &Node, prog: &str, exe: &str) -> String {
    let func = format!("_{}_complete", prog.replace('-', "_"));
    let mut lines: Vec<String> = vec![
        format!("# Generated by {prog} completion install -- do not edit"),
        String::new(),
        format!("{func}() {{"),
        "    local cur prev words cword".into(),
        "    _init_completion 2>/dev/null || {".into(),
        "        COMPREPLY=(); cur=${COMP_WORDS[COMP_CWORD]}; prev=${COMP_WORDS[COMP_CWORD-1]}"
            .into(),
        "        words=(${COMP_WORDS[@]}); cword=$COMP_CWORD".into(),
        "    }".into(),
        String::new(),
        "    # Determine current subcommand path".into(),
        "    local cmd_path=''".into(),
        "    local i".into(),
        "    for ((i=1; i<cword; i++)); do".into(),
        "        case ${words[$i]} in".into(),
        "            -*) ;;".into(),
        "            *) cmd_path=\"${cmd_path:+$cmd_path }${words[$i]}\" ;;".into(),
        "        esac".into(),
        "    done".into(),
        String::new(),
        "    case \"$cmd_path\" in".into(),
    ];
    for case in sorted_cases(root) {
        lines.push(format!("        \"{}\")", case.key));
        let (stat, dynamic) = value_cases(case.node);
        if !stat.is_empty() || !dynamic.is_empty() {
            lines.push("            case \"$prev\" in".into());
            for (f, vals) in &stat {
                lines.push(format!("                {f})"));
                lines.push(format!("                    COMPREPLY=( $(compgen -W \"{vals}\" -- \"$cur\") ); return 0 ;;"));
            }
            for (f, completer, resource) in &dynamic {
                let extra = if *completer == "complete_lookup_query" {
                    " -- \"${COMP_WORDS[@]}\""
                } else {
                    ""
                };
                lines.push(format!("                {f})"));
                lines.push(format!(
                    "                    COMPREPLY=( $(FSV_THIN_COMPLETE=1 {exe} _complete bash {completer} {resource} \"$cur\"{extra}) ); return 0 ;;"
                ));
            }
            lines.push("            esac".into());
        }
        let comps = completions(case.node);
        if !comps.is_empty() {
            lines.push(format!(
                "            COMPREPLY=( $(compgen -W \"{}\" -- \"$cur\") )",
                comps.join(" ")
            ));
        }
        lines.push("            return 0 ;;".into());
    }
    lines.extend([
        "    esac".into(),
        "}".into(),
        String::new(),
        format!("complete -F {func} {prog}"),
    ]);
    lines.join("\n") + "\n"
}

/// `_emit_zsh`.
pub fn emit_zsh(root: &Node, prog: &str, exe: &str) -> String {
    let func = format!("_{}", prog.replace('-', "_"));
    let mut lines: Vec<String> = vec![
        format!("# Generated by {prog} completion install -- do not edit"),
        format!("#compdef {prog}"),
        String::new(),
        format!("{func}() {{"),
        "    local cur prev".into(),
        "    cur=${words[$CURRENT]}".into(),
        "    prev=${words[$CURRENT-1]}".into(),
        String::new(),
        "    local cmd_path=''".into(),
        "    local i".into(),
        "    for ((i=2; i<$CURRENT; i++)); do".into(),
        "        case ${words[$i]} in".into(),
        "            -*) ;;".into(),
        "            *) cmd_path=\"${cmd_path:+$cmd_path }${words[$i]}\" ;;".into(),
        "        esac".into(),
        "    done".into(),
        String::new(),
        "    case \"$cmd_path\" in".into(),
    ];
    for case in sorted_cases(root) {
        lines.push(format!("        \"{}\")", case.key));
        let (stat, dynamic) = value_cases(case.node);
        if !stat.is_empty() || !dynamic.is_empty() {
            lines.push("            case \"$prev\" in".into());
            for (f, vals) in &stat {
                lines.push(format!("                {f})"));
                lines.push(format!("                    compadd {vals}; return 0 ;;"));
            }
            for (f, completer, resource) in &dynamic {
                let extra = if *completer == "complete_lookup_query" {
                    " -- \"${words[@]}\""
                } else {
                    ""
                };
                lines.push(format!("                {f})"));
                lines.push(format!(
                    "                    local _vals; _vals=($( FSV_THIN_COMPLETE=1 {exe} _complete zsh {completer} {resource} \"$cur\"{extra} ))"
                ));
                lines.push("                    compadd -a _vals; return 0 ;;".into());
            }
            lines.push("            esac".into());
        }
        let comps = completions(case.node);
        if comps.is_empty() {
            lines.push("            return 0 ;;".into());
        } else {
            let quoted: Vec<String> = comps.iter().map(|c| q(c)).collect();
            lines.push(format!(
                "            compadd -- {}; return 0 ;;",
                quoted.join(" ")
            ));
        }
    }
    lines.extend(["    esac".into(), "}".into(), String::new(), func]);
    lines.join("\n") + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::gen_tests::{EXE, FISH, PROG, tree};

    fn strings(v: &[&str]) -> Vec<String> {
        v.iter().map(|s| s.to_string()).collect()
    }

    // Expected values: `completion_gen._fish_cond`, `_collect_bash` and
    // `_fish_lines` on the `gen_tests` tree.

    #[test]
    fn fish_cond_matches_python() {
        assert_eq!(fish_cond(&[]), "");
        assert_eq!(
            fish_cond(&strings(&["changes"])),
            "__fish_seen_subcommand_from changes"
        );
        assert_eq!(
            fish_cond(&strings(&["changes", "list"])),
            "__fish_seen_subcommand_from changes; and __fish_seen_subcommand_from list"
        );
        assert_eq!(
            fish_cond(&strings(&["it's"])),
            "__fish_seen_subcommand_from 'it'\"'\"'s'"
        );
    }

    #[test]
    fn collect_and_completions_match_python_cases() {
        let root = tree();
        let mut cases = Vec::new();
        collect(&root, &mut cases);
        let got: Vec<(String, Vec<&str>)> = cases
            .iter()
            .map(|c| (c.key.clone(), completions(c.node)))
            .collect();
        let expected: Vec<(&str, &[&str])> = vec![
            (
                "",
                &[
                    "whoami",
                    "changes",
                    "config",
                    "--verbose",
                    "-v",
                    "--format",
                    "-f",
                ],
            ),
            ("whoami", &["--verbose", "-v", "--store"]),
            ("changes", &["list", "show", "--verbose", "-v", "--debug"]),
            (
                "changes list",
                &[
                    "--verbose",
                    "-v",
                    "--where",
                    "-w",
                    "--kind",
                    "-k",
                    "--limit",
                    "--yes",
                    "-y",
                ],
            ),
            ("changes show", &["--verbose", "-v"]),
            ("config", &["set", "--verbose", "-v"]),
            (
                "config set",
                &["--verbose", "-v", "--key", "--value", "--group"],
            ),
        ];
        assert_eq!(got.len(), expected.len());
        for ((key, comps), (ekey, ecomps)) in got.iter().zip(&expected) {
            assert_eq!(key, ekey);
            assert_eq!(comps.as_slice(), *ecomps, "{key}");
        }
        let keys: Vec<String> = sorted_cases(&root).into_iter().map(|c| c.key).collect();
        assert_eq!(
            keys,
            [
                "changes list",
                "changes show",
                "config set",
                "whoami",
                "changes",
                "config",
                ""
            ]
        );
    }

    #[test]
    fn fish_lines_matches_python() {
        let root = tree();
        let mut lines = Vec::new();
        fish_lines(&root.subcommands[1].subcommands[1], PROG, EXE, &mut lines);
        assert_eq!(
            lines,
            [
                "complete -c my-fsv -f -n '__fish_seen_subcommand_from changes; and __fish_seen_subcommand_from show' -a --verbose",
                "complete -c my-fsv -f -n '__fish_seen_subcommand_from changes; and __fish_seen_subcommand_from show' -a -v",
            ]
        );
        let mut all = Vec::new();
        fish_lines(&root, PROG, EXE, &mut all);
        let body = FISH.splitn(6, '\n').nth(5).expect("fish body");
        assert_eq!(all.join("\n") + "\n", body);
    }
}
