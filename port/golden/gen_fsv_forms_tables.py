"""Generate the CPython-derived lookup tables used by fsv-forms.

Run from the Python worktree so the same CPython build as the reference
implementation produces them:

    cd /Users/phusit.somb/lab/work/fsv && \
      uv run python /Users/phusit.somb/lab/work/fsv-rust/port/golden/gen_fsv_forms_tables.py

Writes ``crates/fsv-forms/src/tables/{casefold,html5,digits}.rs``.
"""
from __future__ import annotations

import html.entities
import html as html_mod
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "crates" / "fsv-forms" / "src" / "tables"
HEADER = (
    "// @generated by port/golden/gen_fsv_forms_tables.py from CPython "
    f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.\n"
)


def rust_str(s: str) -> str:
    out = []
    for ch in s:
        cp = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 0x20 <= cp < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\u{{{cp:x}}}")
    return '"' + "".join(out) + '"'


def casefold() -> str:
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        f = c.casefold()
        if f != c:
            rows.append((cp, f))
    body = "".join(f"    ('\\u{{{cp:x}}}', {rust_str(f)}),\n" for cp, f in rows)
    return HEADER + f"pub(crate) static CASEFOLD: [(char, &str); {len(rows)}] = [\n{body}];\n"


def html5() -> str:
    rows = sorted(html.entities.html5.items())
    body = "".join(f"    ({rust_str(k)}, {rust_str(v)}),\n" for k, v in rows)
    inv = sorted(html_mod._invalid_charrefs.items())
    inv_body = "".join(f"    (0x{k:x}, {rust_str(v)}),\n" for k, v in inv)
    cps = sorted(html_mod._invalid_codepoints)
    cps_body = "".join(f"    0x{c:x},\n" for c in cps)
    return (
        HEADER
        + f"pub(crate) static HTML5: [(&str, &str); {len(rows)}] = [\n{body}];\n\n"
        + f"pub(crate) static INVALID_CHARREFS: [(u32, &str); {len(inv)}] = [\n{inv_body}];\n\n"
        + f"pub(crate) static INVALID_CODEPOINTS: [u32; {len(cps)}] = [\n{cps_body}];\n"
    )


def digits() -> str:
    zeros = []
    for cp in range(0x110000):
        c = chr(cp)
        if unicodedata.category(c) == "Nd" and unicodedata.decimal(c, None) == 0:
            zeros.append(cp)
    body = "".join(f"    0x{z:x},\n" for z in zeros)
    return HEADER + f"/// First code point of each run of Unicode decimal digits 0-9.\npub(crate) static DIGIT_ZEROS: [u32; {len(zeros)}] = [\n{body}];\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "casefold.rs").write_text(casefold())
    (OUT / "html5.rs").write_text(html5())
    (OUT / "digits.rs").write_text(digits())
    print(f"wrote tables to {OUT}")


if __name__ == "__main__":
    main()
