"""Regenerate crates/fsv-py/src/html_entities.rs from CPython's html module
(shared by fsv-core `pystr` and fsv-forms `pytext`).

Run: cd /Users/phusit.somb/lab/work/fsv && uv run python /Users/phusit.somb/lab/work/fsv-rust/port/golden/gen_html_entities.py
"""
import html.entities as he
from html import _invalid_charrefs, _invalid_codepoints
from pathlib import Path

from provenance import header

OUT = Path(__file__).resolve().parents[2] / "crates" / "fsv-py" / "src" / "html_entities.rs"


def lit(s: str) -> str:
    return '"' + "".join(
        c if (c.isascii() and c.isprintable() and c not in '"\\') else "\\u{%x}" % ord(c) for c in s
    ) + '"'


out = [
    "//! CPython `html.entities.html5` (sorted by name), `html._invalid_charrefs`",
    "//! and `html._invalid_codepoints`, for `html.unescape`.",
    "//!",
    "//! Generated by port/golden/gen_html_entities.py; do not edit by hand.",
    f"//! {header()}",
    "",
    "pub static HTML5: &[(&str, &str)] = &[",
]
for k, v in sorted(he.html5.items()):
    out.append(f"    ({lit(k)}, {lit(v)}),")
out.append("];\n")
out.append("pub static INVALID_CHARREFS: &[(u32, &str)] = &[")
for k, v in sorted(_invalid_charrefs.items()):
    out.append(f"    ({k}, {lit(v)}),")
out.append("];\n")
out.append("pub static INVALID_CODEPOINTS: &[u32] = &[")
cps = sorted(_invalid_codepoints)
for i in range(0, len(cps), 12):
    out.append("    " + ", ".join(str(c) for c in cps[i:i + 12]) + ",")
out.append("];")
OUT.write_text("\n".join(out) + "\n")
print(f"wrote {OUT}")
